const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");
const { computeCanonHashFromDisk } = require("../boundary/github-action/src/runtime/computeCanonHash");

function readYaml(absPath) {
  return yaml.load(fs.readFileSync(absPath, "utf8"));
}

function writeChecksums(outPath, files) {
  const lines = files.map((f) => `${f.sha256}  ${f.path}`);
  fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
}

function main() {
  const repoRoot = process.cwd();
  const bundleRoot = path.join(repoRoot, "canon", "bundles", "sp.canon.devwedge", "1.0.0", "bundle");
  const canonPath = path.join(bundleRoot, "canon.index.yaml");

  if (!fs.existsSync(canonPath)) throw new Error(`Missing ${canonPath}`);

  const canon = readYaml(canonPath);
  const canonId = canon?.canon_id;
  const canonVersion = canon?.canon_version;
  if (!canonId || !canonVersion) throw new Error("canon.yaml missing canon_id/canon_version");

  const { hashPayload, canonHash, files } = computeCanonHashFromDisk(
    bundleRoot,
    canonId,
    canonVersion
  );

  const index = {
    ...hashPayload,
    computed: { canon_hash: canonHash },
    notes: "Generated by tools/build-canon-index.js",
  };

  const artifactsDir = path.join(bundleRoot, "artifacts");
  fs.mkdirSync(artifactsDir, { recursive: true });

  const indexPath = path.join(artifactsDir, "bundle.index.json");
  fs.writeFileSync(indexPath, JSON.stringify(index, null, 2) + "\n", "utf8");

  const checksumsPath = path.join(artifactsDir, "checksums.sha256");
  writeChecksums(checksumsPath, files);

  console.log(`canon_hash=${canonHash}`);
  console.log(`wrote ${indexPath}`);
  console.log(`wrote ${checksumsPath}`);
}

main();
